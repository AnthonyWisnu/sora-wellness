const assert=require('node:assert/strict');
const {start,base,pool,f,api,save,screenshot}=require('./browser-common.cjs');
let runtime;
(async()=>{
  runtime=await start('member');const {page,context}=runtime;
  const sessions=await api(context,'/public/sessions?limit=100');
  assert.ok(sessions.some(s=>s.id===f.sessions.priority),'Member dapat melihat sesi 14 hari ke depan');
  const membership=await api(context,'/me/membership');
  const quota=membership.quota.find(r=>r.month===new Date().toISOString().slice(0,7));assert.ok(quota);
  const target=sessions.find(s=>s.id===f.sessions.quota);assert.ok(target);
  await page.goto(base+'/jadwal');
  await page.locator('.zeira-date-options').waitFor();
  const dateName=new Intl.DateTimeFormat('id-ID',{timeZone:'UTC',weekday:'long',day:'numeric',month:'long'}).format(new Date(target.localDate+'T12:00:00Z'));
  await page.getByRole('button',{name:new RegExp('^'+dateName+', ')}).click();
  const card=page.locator('.zeira-session-card').filter({has:page.getByRole('heading',{name:'Pilates Member Penelitian',exact:true})});
  await card.getByRole('button',{name:'Pesan kelas',exact:true}).click();
  await page.getByRole('radio',{name:/Pakai jatah member/}).waitFor();
  assert.equal(await page.getByRole('radio',{name:/Pakai jatah member/}).isChecked(),true);
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/v1/bookings')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Konfirmasi reservasi',exact:true}).click();
  const response=await responsePromise;assert.equal(response.status(),201);
  const booking=await response.json();assert.equal(booking.status,'confirmed');assert.equal(booking.source,'quota');
  const options=await api(context,`/sessions/${target.id}/booking-options`);
  assert.equal(options.quotaUsed,quota.used+1);
  await page.goto(base+'/dashboard/bookings');
  await page.getByRole('button',{name:'E-Ticket QR',exact:true}).waitFor();
  await page.getByRole('button',{name:'E-Ticket QR',exact:true}).click();
  await page.getByRole('dialog').getByRole('img',{name:new RegExp('QR Pass')}).waitFor();
  await screenshot(page,'01-member-booking');
  assert.deepEqual(runtime.errors,[]);
  save('member-booking-results',{result:'PASS',memberWindowDays:30,prioritySessionVisible:true,bookingId:booking.id,source:booking.source,status:booking.status,quotaBefore:quota.used,quotaAfter:options.quotaUsed,qrVisible:true,browserErrors:runtime.errors});
  console.log('PASS: member 30 hari, booking kuota, potong tepat satu jatah, tiket QR tampil');
})().catch(error=>{console.error(error.stack);process.exitCode=1}).finally(async()=>{if(runtime)await runtime.browser.close();await pool.end()});
