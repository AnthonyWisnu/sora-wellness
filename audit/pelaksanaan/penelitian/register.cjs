const crypto=require('node:crypto'),assert=require('node:assert/strict'),path=require('node:path');
const {root,pool,save,base}=require('./browser-common.cjs');
const {chromium}=require(path.join(root,'frontend/node_modules/playwright-core'));
let browser;
(async()=>{
  await pool.query('DELETE FROM rate_limit_buckets');
  browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const page=await browser.newPage({viewport:{width:375,height:812}});page.setDefaultTimeout(12000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const email='register-'+crypto.randomUUID()+'@example.test',password='PenelitianSora_2026_TestOnly';
  await page.goto(base+'/masuk');
  await page.getByRole('button',{name:'Belum punya akun? Daftar di sini',exact:true}).click();
  await page.getByLabel('Nama lengkap',{exact:true}).fill('Pelanggan Registrasi Penelitian');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Kata sandi',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Daftar dan masuk',exact:true}).click();
  await page.getByRole('heading',{name:'Ringkasan',exact:true}).waitFor();
  const me=await page.request.get(base+'/api/v1/me');assert.equal(me.status(),200);assert.equal((await me.json()).role,'customer');
  await page.getByRole('button',{name:'Buka menu dashboard',exact:true}).click();
  const loggedOut=page.waitForResponse(r=>r.url().endsWith('/api/v1/auth/logout')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Keluar',exact:true}).click();
  assert.equal((await loggedOut).status(),204);
  assert.equal((await page.request.get(base+'/api/v1/me')).status(),401);
  await page.goto(base+'/masuk');
  await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Kata sandi',{exact:true}).fill(password);
  await page.getByRole('main').getByRole('button',{name:'Masuk',exact:true}).click();
  await page.getByRole('heading',{name:'Ringkasan',exact:true}).waitFor();
  assert.equal((await page.request.get(base+'/api/v1/me')).status(),200);assert.deepEqual(errors,[]);
  save('register-results',{result:'PASS',viewport:375,registration:true,customerRole:true,logoutRevokesSession:true,loginAgain:true,browserErrors:errors});
  console.log('PASS: registrasi, login dan logout pada lebar 375px');
})().catch(error=>{console.error(error.stack);process.exitCode=1}).finally(async()=>{if(browser)await browser.close();await pool.end()});
