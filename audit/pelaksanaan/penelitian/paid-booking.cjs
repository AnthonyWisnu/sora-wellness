const assert=require('node:assert/strict');
const {start,base,pool,f,api,save,screenshot,qaOrder}=require('./browser-common.cjs');
const paySandbox=require('./sandbox-payment.cjs');
let runtime;
(async()=>{
  runtime=await start('guest');const {page,context}=runtime;
  const sessions=await api(context,'/public/sessions?limit=100');
  assert.equal(sessions.some(s=>s.id===f.sessions.priority),false,'Pelanggan tanpa paket dibatasi 7 hari');
  const denied=await context.request.get(base+`/api/v1/sessions/${f.sessions.priority}/booking-options`);
  assert.ok([200,409].includes(denied.status()));if(denied.ok())assert.equal((await denied.json()).bookable,false);
  const target=sessions.find(s=>s.id===f.sessions.paid);assert.ok(target);
  await page.goto(base+'/jadwal');await page.locator('.zeira-date-options').waitFor();
  const dateName=new Intl.DateTimeFormat('id-ID',{timeZone:'UTC',weekday:'long',day:'numeric',month:'long'}).format(new Date(target.localDate+'T12:00:00Z'));
  await page.getByRole('button',{name:new RegExp('^'+dateName+', ')}).click();
  const card=page.locator('.zeira-session-card').filter({has:page.getByRole('heading',{name:'Yoga Dasar Penelitian',exact:true})}).filter({hasText:'Rp75.000'});
  await card.getByRole('button',{name:'Pesan kelas',exact:true}).click();
  const pending=page.waitForResponse(r=>r.url().endsWith('/api/v1/bookings')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Konfirmasi reservasi',exact:true}).click();
  const response=await pending;assert.equal(response.status(),201);
  const order=await response.json();assert.equal(order.status,'pending_payment');qaOrder('booking',order);
  await page.getByRole('heading',{name:'Lanjutkan pembayaran',exact:true}).waitFor();
  await screenshot(page,'booking-payment-dialog');
  const settlement=await paySandbox(runtime,order,'booking');
  await page.goto(base+'/dashboard/bookings');
  await page.getByRole('button',{name:'E-Ticket QR',exact:true}).waitFor();
  await page.getByRole('button',{name:'Batalkan',exact:true}).click();
  const confirm=page.getByRole('dialog');await confirm.getByRole('heading',{name:'Batalkan booking?',exact:true}).waitFor();
  await confirm.getByRole('button',{name:'Batalkan booking',exact:true}).click();
  await page.getByText('Dibatalkan',{exact:true}).waitFor();
  const wallet=await api(context,'/me/wallet');assert.equal(wallet.balanceIdr,75000);
  await api(context,`/bookings/${order.id}/cancel`,'POST');
  assert.equal((await api(context,'/me/wallet')).balanceIdr,75000);
  save('paid-booking-results',{...settlement,guestWindowDays:7,prioritySessionVisible:false,paymentDialogVisible:true,bookingId:order.id,cancellation:'PASS',walletAfterCancellation:wallet.balanceIdr,duplicateCancellation:'no extra credit',browserErrors:runtime.errors});
  assert.deepEqual(runtime.errors,[]);console.log('PASS: pelanggan 7 hari, dialog tetap terbuka, Sandbox settled, tiket, batal dan refund wallet sekali');
})().catch(error=>{console.error(error.stack);process.exitCode=1}).finally(async()=>{if(runtime)await runtime.browser.close();await pool.end()});
