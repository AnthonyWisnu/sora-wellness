const assert=require('node:assert/strict');
const {start,base,pool,f,api,save,screenshot}=require('./browser-common.cjs');
let runtime;
(async()=>{
  runtime=await start('admin');const {page,context}=runtime;
  await page.goto(base+'/dashboard/classes');
  await page.getByRole('button',{name:'Tambah jenis kelas',exact:true}).click();
  let dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nama kelas',{exact:true}).fill('Yoga Restoratif '+f.suffix);
  await dialog.getByLabel('Kategori',{exact:true}).fill('Yoga');
  await dialog.getByLabel('Deskripsi',{exact:true}).fill('Kelas latihan pemulihan untuk demonstrasi sistem studio.');
  await dialog.getByLabel('Harga satuan bawaan (Rp)',{exact:true}).fill('50000');
  const classResponse=page.waitForResponse(r=>r.url().endsWith('/api/v1/admin/class-types')&&r.request().method()==='POST');
  await dialog.getByRole('button',{name:'Simpan kelas',exact:true}).click();
  const createdClass=await classResponse;assert.equal(createdClass.status(),201);const classId=(await createdClass.json()).id;
  await dialog.waitFor({state:'hidden'});
  await page.goto(base+'/dashboard/manage');
  await page.getByRole('button',{name:'Buat sesi',exact:true}).click();dialog=page.getByRole('dialog');
  await dialog.getByRole('combobox',{name:'Jenis kelas',exact:true}).selectOption(classId);
  await dialog.getByRole('combobox',{name:'Pelatih',exact:true}).selectOption(f.users.coach.id);
  const date=(await pool.query("SELECT ((now() AT TIME ZONE timezone)::date+5)::text AS date FROM studio WHERE id=1")).rows[0].date;
  await dialog.getByLabel('Tanggal kelas',{exact:true}).fill(date);
  await dialog.getByLabel('Jam mulai',{exact:true}).fill('11:00');
  await dialog.getByLabel('Kapasitas',{exact:true}).fill('10');
  const sessionResponse=page.waitForResponse(r=>r.url().endsWith('/api/v1/admin/sessions')&&r.request().method()==='POST');
  await dialog.getByRole('button',{name:'Simpan sesi',exact:true}).click();
  const created=await sessionResponse;assert.equal(created.status(),201);const sessionId=(await created.json()).id;
  await dialog.waitFor({state:'hidden'});
  await page.getByLabel('Pilih tanggal kalender',{exact:true}).fill(date);
  let row=page.locator('article.admin-record').filter({hasText:'Yoga Restoratif '+f.suffix});
  await row.getByRole('button',{name:'Ubah',exact:true}).click();dialog=page.getByRole('dialog');
  await dialog.getByLabel('Kapasitas',{exact:true}).fill('12');
  const editResponse=page.waitForResponse(r=>r.url().endsWith('/api/v1/admin/sessions/'+sessionId)&&r.request().method()==='PATCH');
  await dialog.getByRole('button',{name:'Simpan sesi',exact:true}).click();assert.equal((await editResponse).status(),200);
  await dialog.waitFor({state:'hidden'});await row.getByText(/12 kursi/).waitFor();
  await screenshot(page,'02-admin-sessions');
  await row.getByRole('button',{name:'Batalkan',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Batalkan sesi',exact:true}).click();
  await row.getByText(/DIBATALKAN/).waitFor();
  assert.equal((await pool.query('SELECT status FROM class_sessions WHERE id=$1',[sessionId])).rows[0].status,'cancelled');
  await page.goto(base+'/dashboard/lockers');
  const locker=await api(context,'/admin/lockers','POST',{code:'STUDI-'+f.suffix.toUpperCase()});
  await page.reload();
  const lockerCard=page.locator('article').filter({hasText:'STUDI-'+f.suffix.toUpperCase()});
  await lockerCard.getByRole('button',{name:/Tetapkan/}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByPlaceholder('Ketik nama atau email member...').fill(f.users.member.email);
  await dialog.getByRole('button',{name:/Ayu Penelitian/}).click();
  const assign=page.waitForResponse(r=>r.url().endsWith('/assignment')&&r.request().method()==='PUT');
  await dialog.getByRole('button',{name:/Tetapkan ke Loker/}).click();assert.equal((await assign).status(),200);
  await dialog.waitFor({state:'hidden'});await lockerCard.getByText('Ayu Penelitian',{exact:true}).waitFor();
  save('admin-studio-results',{result:'PASS',classId,sessionId,createClass:true,createSession:true,editSession:true,cancelSession:true,lockerId:locker.id,lockerCode:'STUDI-'+f.suffix.toUpperCase(),lockerAssignedTo:f.users.member.id,browserErrors:runtime.errors});
  assert.deepEqual(runtime.errors,[]);console.log('PASS: admin membuat kelas/sesi, mengubah kapasitas, membatalkan sesi dan menetapkan loker member');
})().catch(async error=>{console.error(error.stack);if(runtime){console.log((await runtime.page.locator('body').ariaSnapshot()).slice(0,5500));await screenshot(runtime.page,'admin-failure')}process.exitCode=1}).finally(async()=>{if(runtime)await runtime.browser.close();await pool.end()});
